static void rf_predict_proba(
    const double x[RF_N_FEATURES],
    double outProba[RF_N_CLASSES]
) {
    for (int c = 0; c < RF_N_CLASSES; ++c) {
        outProba[c] = 0.0;
    }

    for (int t = 0; t < RF_N_TREES; ++t) {
        uint16_t node = RF_TREE_ROOTS[t];

        while (RF_FEATURE[node] >= 0) {
            int f = RF_FEATURE[node];

            if (x[f] <= RF_THRESHOLD[node]) {
                node = RF_LEFT[node];
            } else {
                node = RF_RIGHT[node];
            }
        }

        double total = 0.0;
        for (int c = 0; c < RF_N_CLASSES; ++c) {
            total += RF_NODE_VALUES[node][c];
        }

        if (total > 0.0) {
            for (int c = 0; c < RF_N_CLASSES; ++c) {
                outProba[c] += RF_NODE_VALUES[node][c] / total;
            }
        }
    }

    for (int c = 0; c < RF_N_CLASSES; ++c) {
        outProba[c] /= RF_N_TREES;
    }
}

static uint8_t rf_predict(
    const double x[RF_N_FEATURES],
    double outProba[RF_N_CLASSES]
) {
    rf_predict_proba(x, outProba);

    uint8_t best = 0;
    for (uint8_t c = 1; c < RF_N_CLASSES; ++c) {
        if (outProba[c] > outProba[best]) {
            best = c;
        }
    }
    return best;
}
